// NexWeave 生成文本分句契约。
//
// 职责：把 LLM（Large Language Model，大语言模型）的增量 token 流切成“可以立刻送去
// 合成的最小完整片段”，使首段音频的合成与播放不必等待整段回答生成结束。它只做字节级
// 切分，不做分词、不做语义改写、不访问模型、设备、线程或真实时间。
//
// 为什么需要这一层：后端只保证“token 有序”，不保证 token 恰好落在句子边界上；一次
// 合成调用又必须拿到非空文本。若把两者直接相连，就只能等全部 token 到齐后再合成，
// 从而丢失“生成未结束即开始播放”的重叠能力；若按 token 边界切分，又会把半个汉字
// 送给合成器。本契约把“何时可以切”固定成显式规则，使重叠行为可以用事件顺序断言，
// 而不是靠墙钟偶然时序。
//
// 字节归属（完整性不变量）：把交付的片段按顺序拼接、再加上交付时刻“仍是未完成序列”
// 的那些尾部字节，即等于生成侧提交过的全部字节。也就是说切分不丢实质内容；被有意丢弃
// 的只有句首/重复的标点与换行符，它们不承载语义，且丢弃事实由切分位置本身表达。
//
// 输入前提：调用方按 token 到达顺序把每个 token 的原始字节原样交给 feed()，不重排、
// 不跳字节、不预先做编码转换；token 边界与 UTF-8 字符边界无关。flush() 只能在生成
// 正常结束时调用一次；取消或失败路径应丢弃对象而不是 flush，避免把截断的尾部当成
// 完整句子合成出来。
//
// 并发：本类不含线程、条件变量与真实时钟，同一实例由调用方串行调用，不提供内部同步。
// 资源：只拥有标准库字符串缓冲，不创建文件、socket、线程或设备句柄；分配失败按标准库
// 异常向上传播，抛出时缓冲保持原值（emitted 列表可能已追加过内容，调用方应放弃本轮）。
// 版本：本契约是 v1，字段单位统一为“字节”而不是“字符”或“token”，因为上限要直接约束
// 下游合成器的输入长度，而字节数是唯一与编码无关的稳定量。
#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace nexweave::runtime {

// 文本片段被切出的原因。它只解释“为什么在这里切开”，不代表片段质量或语义完整度。
enum class TextChunkReason : std::uint8_t {
  // 遇到句末标点（含换行符）：这是首选的切分时刻，片段语义最完整。
  kTerminator,
  // 缓冲字节数达到 max_chunk_bytes：无标点的长文本必须被强制切开，否则合成器要等到
  // 整段生成结束才能开始，重叠能力会退化为串行。
  kMaxBytes,
  // 生成正常结束时的收尾刷新：把不足一句的尾段交付，避免整段回答的最后一句丢失。
  kFlushed
};

// 一个可立即合成的文本片段。
//
// 拼接不变量：按 emitted 顺序把 text 首尾相连，再补上“因切分点被丢弃的字符”，即得到
// 生成侧提交过的全部字节。本版被丢弃的字符只有两类：切分点之后多余的句末标点，以及
// 换行符（它只切分、不进入文本）。因此片段有序、不重复、不遗漏。
//
// 所有权：text 是独立副本，源 token 可以立即释放。
struct TextChunk {
  std::string text;
  TextChunkReason reason = TextChunkReason::kTerminator;
};

// 流式分句器：把 token 字节流切成有界的文本片段。
//
// 切分规则（确定性、可测试）：
//   1. 句末标点 。！？!?;；与换行符 \n 触发切分；标点归属于前一片段，换行符不进入文本。
//   2. 连续句末标点只保留首个：第二个及之后的标点被丢弃，避免产出只含标点的空句。
//   3. 片段永远不以标点开头（句首标点丢弃）；这与规则 2 是同一件事的两个说法。
//   4. 非句末标点（逗号、顿号、冒号等）不切分，它们只累积字节。
//   5. 缓冲累计字节数达到 max_chunk_bytes 时立即切分（reason=kMaxBytes），不等标点，
//      也不等下一次 feed。若推迟到“下一个字符到来才发现装不下”，一段正好填满上限的文本
//      会一直留在缓冲里，它的交付时机就取决于下一次生成何时发生。
//   6. 切分点永远落在 UTF-8 字符边界上：任何片段都不会包含半个多字节字符。多字节字符
//      整体判断“放得下还是放不下”，放不下就把整个字符推到下一片段。
//   7. 容量判定先于字符追加、句末标点判定先于容量判定：因此标点始终归属有内容的那一段，
//      不会出现“因为刚好达到上限，标点被推到下一片段开头”的情况。
//   8. 片段内部不会以标点开头，因此“第一句。”之前的孤立标点、以及切分点之后重复到达的
//      标点都被丢弃；被丢弃的字节只有标点与换行符，实质文本一字不丢。
//
// 状态载体：内部只有一个布尔量记录“上一片段是否正好在缓冲末尾切开”。它为真时到达的
// 句末标点视为句首标点；任何实质字符被追加时清零。之所以需要显式记录而不是靠“缓冲是否
// 为空”判断：容量切分之后缓冲同样为空，若把紧随其后的标点当作新片段起点，就会产出只含
// 标点的空句，让合成器白白起一轮。
//
// 容量不变量（每次 feed/flush 返回后成立）：内部缓冲字节数 <= max_chunk_bytes + 3。
// 尾部多出的最多 3 字节来自“剩余空间装不下下一个完整字符”：此时若强切就会产出非法序列，
// 因此把该字符留在缓冲里等待后续字节，代价是常数级（一个 UTF-8 字符最长 4 字节）的上界
// 放宽，而不是与输入长度相关的增长。
//
// 未完成序列：实时生成中，最后一个 token 可能停在多字节字符中间，此时缓冲里会有不完整
// 序列，这不是错误而是正常的中间状态。若生成结束时仍是这种状态，说明文本本身不是合法
// UTF-8；incomplete_utf8() 会报出该事实，由调用方决定拒绝本轮，而不是悄悄丢掉半截字节。
// 判定方式是对缓冲做一次完整 UTF-8 校验，而不是只看末尾字节：合法字符也可以以续字节
// 收尾（例如“见”= E8 A7 81），只看末字节会把完整文本误判成截断。
class TextChunker final {
 public:
  // max_chunk_bytes 是单个片段的字节上限；0 表示不限制长度，只按标点切分（仅用于
  // 受控测试，长回答会在一次合成中占用与文本等量的内存）。取值只影响切分位置，
  // 不影响最终拼接出的字节内容。
  explicit TextChunker(std::size_t max_chunk_bytes = 60) noexcept;

  // 送入一段增量 token 字节，按到达顺序追加到 emitted 尾部。
  // 输入前提：text 是本次 token 的原始字节，可以停在字符中间。
  // 输出后置：emitted 追加本次切出的全部片段（可能为空），顺序与切分位置一致。
  // 错误语义：本函数不产生错误码；内存不足时抛出并由调用方放弃本轮。
  void feed(const std::string& text, std::vector<TextChunk>& emitted);

  // 生成正常结束时的收尾刷新：把缓冲里的尾段作为一个片段交付（若缓冲为空则什么都不做），
  // 并清空缓冲。幂等：连续调用第二次不会再产出内容，因此不会重复合成同一段回答。
  // 取消或失败路径不得调用本函数：那些路径下尾段是否完整无法确认，只应丢弃缓冲。
  void flush(std::vector<TextChunk>& emitted);

  // ---- 只读观测：不改变分句状态，供测试与运行证据核对 ----

  // 尚未切出的缓冲字节数（<= max_chunk_bytes + 3）。
  std::size_t buffered_bytes() const noexcept;
  // 已交付的片段总数（不含尚未切出的缓冲）。
  std::size_t emitted_chunks() const noexcept;
  // 缓冲末尾是否停在未收完的 UTF-8 序列上；正常中间状态为真，生成结束仍为真表示文本非法。
  bool incomplete_utf8() const noexcept;
  // 单个片段的字节上限配置值；0 表示不限长。
  std::size_t max_chunk_bytes() const noexcept;

 private:
  // 立即交付当前缓冲（缓冲必须非空），并追加 reason。
  void emit(TextChunkReason reason, std::vector<TextChunk>& emitted);

  std::size_t max_chunk_bytes_ = 60;
  std::string buffer_;
  // 上一次切分是否正好发生在缓冲末尾：为真表示“下一片段的开头还没有内容”，此时到达的
  // 句末标点属于句首标点，必须丢弃。它是“连续标点只保留首个”与“片段不以标点开头”两条
  // 规则的唯一状态载体，任何普通字符被追加时清零。
  bool split_pending_ = false;
  std::size_t emitted_chunks_ = 0;
};

// 校验一个字符串是否是完整、规范的 UTF-8 序列（不接受过长编码、代理区与超过 U+10FFFF）。
// 用途：在把 LLM 的最终文本交给合成器之前做一次显式检查，避免把非法字节送进下游。
// 空串视为合法（零个字符本身就是完整序列）。本函数无分配、无状态、不抛异常。
bool is_valid_utf8(const std::string& text) noexcept;

}  // namespace nexweave::runtime
